#include <errno.h>
#include <stdint.h>
#include <stddef.h>

/* Символы, генерируемые линкером ARM из scatter-файла.
 * Имя RW_IRAM1 должно совпадать с именем региона в .sct. */
extern uint32_t Image$$RW_IRAM1$$ZI$$Limit;
extern uint32_t Image$$RW_IRAM1$$Base;

/* Границы кучи. Стек (ARM_LIB_STACK) располагается в конце RAM,
 * поэтому кучу ограничиваем сверху началом стека (0x10048000 - 0x400 = 0x10047C00). */
#define HEAP_BASE   ((uint8_t *)&Image$$RW_IRAM1$$ZI$$Limit)
#define HEAP_LIMIT  ((uint8_t *)0x10047C00)  /* 0x10048000 - 0x400 (stack) */

static uint8_t *heap_end = NULL;

/**
  * @brief  _sbrk — расширение кучи (используется malloc/free из ARM C Library)
  * @param  incr — сколько байт запросить
  * @retval указатель на начало выделенного блока, либо (void*)-1 при ошибке
  */
void *_sbrk(int incr)
{
    uint8_t *prev_heap_end;

    if (heap_end == NULL) {
        heap_end = HEAP_BASE;
    }

    prev_heap_end = heap_end;

    /* Проверка на переполнение (как при incr > 0, так и при incr < 0) */
    if ((incr > 0 && (heap_end + incr > HEAP_LIMIT)) ||
        (incr < 0 && (heap_end + incr < HEAP_BASE))) {
        errno = ENOMEM;
        return (void *)-1;
    }

    heap_end += incr;
    return (void *)prev_heap_end;
}

/* Опционально: заглушка _write, если используется printf через semihosting */
int _write(int file, char *ptr, int len)
{
    (void)file;
    (void)ptr;
    return len;   /* перенаправьте на ваш UART, если нужно */
}

