/*
 * i2c2.h
 *
 *  Раздел работы с интерфейсом I2C2 (STM32H747IITx, ядро Cortex-M4).
 *
 *  Выводы:  PF0 - I2C2_SDA, PF1 - I2C2_SCL (AF4, открытый сток).
 *  Тактирование: D2PCLK1 = 120 МГц, TIMINGR = 0x307075B1 (~100 кГц).
 *
 *  Раздел самодостаточен: выводы, тактирование и настройка периферии
 *  выполняются в I2C2_Init(), поэтому перегенерация проекта в CubeMX
 *  не ломает интерфейс. I2C1 (PB7/PB8, BQ32000) и остальная программа
 *  не затрагиваются.
 */

#ifndef I2C2_H
#define I2C2_H

#include "main.h"
#include <stdint.h>

/* ---------------------------------------------------------------------------
 * Аппаратная конфигурация интерфейса
 * ------------------------------------------------------------------------ */

#define I2C2_SDA_GPIO_Port      GPIOF
#define I2C2_SDA_Pin            GPIO_PIN_0
#define I2C2_SCL_GPIO_Port      GPIOF
#define I2C2_SCL_Pin            GPIO_PIN_1
#define I2C2_GPIO_AF            GPIO_AF4_I2C2

/* TIMINGR для 100 кГц при тактовой частоте ядра I2C 120 МГц.
   Значение совпадает с I2C2.Timing в pu_new.ioc. */
#define I2C2_TIMING             0x307075B1U

/* Тайм-ауты HAL, мс */
#define I2C2_TIMEOUT_MS         50U
#define I2C2_PROBE_TIMEOUT_MS   10U

/* Сканирование: адреса 0x08..0x77 (7-битные, как в документации на микросхемы) */
#define I2C2_ADDR_FIRST         0x08U
#define I2C2_ADDR_LAST          0x77U
#define I2C2_ADDR_INVALID       0x00U
#define I2C2_MAX_DEVICES        (I2C2_ADDR_LAST + 1U)

/* ---------------------------------------------------------------------------
 * Результаты операций
 * ------------------------------------------------------------------------ */

typedef enum {
	I2C2_RES_OK = 0,     /* операция выполнена */
	I2C2_RES_ERROR,      /* ошибка шины/периферии */
	I2C2_RES_TIMEOUT,    /* нет ответа за отведённое время */
	I2C2_RES_NACK,       /* устройство не подтвердило адрес/данные */
	I2C2_RES_BUSY,       /* периферия занята */
	I2C2_RES_PARAM,      /* неверный параметр */
	I2C2_RES_NOT_INIT    /* раздел не инициализирован */
} I2C2_Result;

/* ---------------------------------------------------------------------------
 * Инициализация и состояние
 * ------------------------------------------------------------------------ */

/* Настраивает GPIO (PF0/PF1, AF4, открытый сток), тактирование и периферию.
   Возвращает TRUE при успехе. Повторный вызов безопасен. */
BOOL I2C2_Init(void);

/* TRUE, если раздел инициализирован и готов к обмену */
BOOL I2C2_IsReady(void);

/* HAL-дескриптор I2C2 (для нестандартных сценариев) */
I2C_HandleTypeDef *I2C2_Handle(void);

/* Результат последней операции */
I2C2_Result I2C2_LastResult(void);

/* Строковое представление результата: "OK", "NACK", "TIMEOUT", ... */
const char *I2C2_ResultStr(I2C2_Result res);

/* Текущее состояние линий: бит 0 - SDA, бит 1 - SCL (1 - высокий уровень) */
uint8_t I2C2_Lines(void);

/* ---------------------------------------------------------------------------
 * Обмен данными (адреса 7-битные, как в документации)
 * ------------------------------------------------------------------------ */

/* Проверка присутствия устройства на шине */
I2C2_Result I2C2_Probe(uint8_t addr);

/* Поиск всех устройств на шине.
   devices/capacity - буфер под найденные адреса (может быть NULL),
   count - сколько адресов найдено (обязательный). */
I2C2_Result I2C2_Scan(uint8_t *devices, uint16_t capacity, uint16_t *count);

/* Запись/чтение без адреса регистра */
I2C2_Result I2C2_Write(uint8_t addr, const uint8_t *data, uint16_t size);
I2C2_Result I2C2_Read(uint8_t addr, uint8_t *data, uint16_t size);

/* Запись/чтение с 8-битным адресом регистра (типовые микросхемы) */
I2C2_Result I2C2_WriteReg8(uint8_t addr, uint8_t reg, const uint8_t *data, uint16_t size);
I2C2_Result I2C2_ReadReg8(uint8_t addr, uint8_t reg, uint8_t *data, uint16_t size);

/* То же для одного байта - удобно при отладке */
I2C2_Result I2C2_WriteReg8Byte(uint8_t addr, uint8_t reg, uint8_t value);
I2C2_Result I2C2_ReadReg8Byte(uint8_t addr, uint8_t reg, uint8_t *value);

/* ---------------------------------------------------------------------------
 * Восстановление шины
 * ------------------------------------------------------------------------ */

/* Освобождает "залипшую" шину (9 тактов SCL + STOP) и заново включает I2C2.
   Нужен, если обмен был прерван сбросом МК или помехой. */
I2C2_Result I2C2_BusRecover(void);

/* ---------------------------------------------------------------------------
 * Консоль
 * ------------------------------------------------------------------------ */

/* Обработчик команды консоли "I2C2 ..." (SCAN, INFO, PING, RD, WR, RECOVER).
   Вызывается из console_rcv(); сама печатает результат. */
void I2C2_Console(char *msg);

#endif /* I2C2_H */
