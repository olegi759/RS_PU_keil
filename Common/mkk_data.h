// ---- Результат контроля исправности линий оповещения ----, Для web: код - цифра внутри цветового индикатора
//Неизвестно. Для web: Цвет серый, код - 0 (128)
#define MKK_LIN_STATE_UNKNOW				0x80
//Линия исправна. Для web: Цвет зеленый, код - 1 (129)
#define MKK_LIN_STATE_OK					0x81
//Обрыв. Для web: Цвет красный, код - 2  (130)
#define MKK_LIN_STATE_BREAK					0x82
//Линия неисправна, сопротивление линии увеличено (или сопротивление линии выше нормы при инсталляции). Для web: Цвет красный, код - 3 (131)
#define MKK_LIN_STATE_UP					0x83
//Линия неисправна, сопротивление линии снижено (или сопротивление линии меньше нормы при инсталляции). Для web: Цвет красный, код - 4 (132)
#define MKK_LIN_STATE_DOWN					0x84
//КЗ линии. Для web: Цвет красный, код - 5 (133)
#define MKK_LIN_STATE_SHORT_CIRCUIT			0x85
	

// ---- Результат контроля исправности входов сигнализации  ----, Для web: код - цифра внутри цветового индикатора
