#define MKK_INSIG_STATE_NORM_NO_SIGNAL		0x92
//Неисправность зона неопределенности, сопротивление 3…4 кОм. Для web: Цвет красный, код - 3
#define MKK_INSIG_STATE_UNCERTAINTY			0x93
//Норма сигнал есть, сопротивление 2,35 кОм (2…3 кОм). Для web: Цвет зеленый, код - 4
#define MKK_INSIG_STATE_NORM_YES_SIGNAL		0x94
//Неисправность КЗ, сопротивление линии менее 2 кОм. Для web: Цвет красный, код - 5
#define MKK_INSIG_STATE_SHORT_CIRCUIT		0x95


// ---- Результат контроля исправности входа запуска  ----
