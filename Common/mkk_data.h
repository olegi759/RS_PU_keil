//Скорость 115200.
//UART 9 bit. девятый бит устанавливается только в первом байте.
//CRC - 16 битное (2 байта) значение контрольной суммы (uint16_t), считается как сумма всех байтов от 0 байта до CRC (старший байт вперед)
//Комманда - 8 битное значение (1 байт uint8_t) принимает значение от 0 до 127
//Данные комманды - байты параметров комманды (могут отсутствовать)
//Данные ответа на комманду - байты ответа на комманду (могут отутствовать)
//Код ошибки - 1 байт (uint8_t) кода ошибки 
//В битовых полях младший бит первая линия
//В байтовых массивах первый байт первая линия
//длина пакета данных BYTE_COUNT (uint8_t)
//если данных нет BYTE_COUNT==0

//Запрос: [Комманда][BYTE_COUNT][ ..... Данные комманды .....][CRC]
//Ответ ОК:  [Комманда][BYTE_COUNT][ ..... Данные ответа на комманду .....][CRC]
//Ответ ERROR:  [0x80 | Комманда][BYTE_COUNT][Код ошибки][CRC]

